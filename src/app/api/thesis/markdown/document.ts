/** THESIS.md, assembled from the thesis sections and reference parts. */
import { captureSection } from "@/app/api/thesis/markdown/capture";
import { demandSection } from "@/app/api/thesis/markdown/demand";
import { FOOTER, sectionHeading, type ThesisDocumentInput } from "@/app/api/thesis/markdown/format";
import { leadLagSection } from "@/app/api/thesis/markdown/lead-lag";
import { networkSection } from "@/app/api/thesis/markdown/network";
import { peersSection } from "@/app/api/thesis/markdown/peers";
import { aboutTheData, couldNotCompute, FORMULAS, howToRerun } from "@/app/api/thesis/markdown/reference";
import { supplySection } from "@/app/api/thesis/markdown/supply";
import { technologySection } from "@/app/api/thesis/markdown/technology";
import { valuationSection } from "@/app/api/thesis/markdown/valuation";
import { LIVE_DASHBOARD_URL } from "@/config/site";
import { PILLARS, SECTION_ORDER, SECTIONS, THESIS_STATEMENT, THESIS_STEPS } from "@/content/thesis";
import { thesisVerdict } from "@/lib/thesis/verdict";

/** The verdict on the data: its summary in bold, then the evidence it rests on as a list. */
function verdict(input: ThesisDocumentInput): string {
  const v = thesisVerdict(input.metrics);
  /** The summary is bold as a whole, so the spans marked bold inside it are set in italics instead. */
  return v ? `**${v.summary.replaceAll("**", "*")}**\n\n${v.points.map((point) => `- ${point}`).join("\n")}` : "The database does not cover the numbers the verdict needs yet.";
}

/** The document's opening, laid out like the README: a centred title, the disclaimer, the banner and the two links. */
function header(): string {
  const live = LIVE_DASHBOARD_URL.replace(/^https?:\/\//, "");
  return [
    '<div align="center">',
    "# NEAR Long-Term Investment Thesis",
    "*For research and education only. This is not investment, financial or legal advice.*",
    '<img src="assets/thesis-banner.svg" width="100%" alt="NEAR Long-Term Investment Thesis: NEAR Intents turns cross-chain trading into buying of NEAR on the open market." />',
    `**Live dashboard: [${live}](${LIVE_DASHBOARD_URL})** · **Guide: [README.md](README.md)**`,
    "</div>",
  ].join("\n\n");
}

/** THESIS.md, rendered from the database and the section content in src/content/thesis.ts. */
export function thesisDocument(input: ThesisDocumentInput): string {
  const sections = SECTION_ORDER.map((id, i) => `${i + 1}. ${PILLARS.has(id) ? `**${SECTIONS[id].title}.**` : `**${SECTIONS[id].eyebrow}:** ${SECTIONS[id].title}.`}`);
  return (
    [
      "<!-- Generated by `npm run thesis` from GET /api/thesis. Edit src/content/, src/lib/thesis/ or src/app/api/thesis/markdown/, not this file. -->",
      header(),
      sectionHeading("Verdict", "⚖️"),
      verdict(input),
      sectionHeading("The thesis", "💡"),
      `**${THESIS_STATEMENT}**`,
      `The case rests on ${PILLARS.size} pillars, followed by the valuation and ${SECTION_ORDER.length - PILLARS.size - 1} supporting theses:`,
      sections.join("\n"),
      "How it works:",
      THESIS_STEPS.map((step, i) => `${i + 1}. ${step}`).join("\n"),
      "Each section below states the claim and its numbers, then the bull case (the evidence for it) and the bear case (the evidence against it), then the breaking point (the result that would change the view), whether the data shows it, and how to re-run the numbers. The dashboard shows the same sections with live data.",
      aboutTheData(input),
      demandSection(input),
      captureSection(input),
      supplySection(input),
      valuationSection(input),
      technologySection(input),
      networkSection(input),
      peersSection(input),
      leadLagSection(input),
      couldNotCompute(input),
      howToRerun(),
      sectionHeading("Formulas", "🧮"),
      FORMULAS.map((formula) => `- ${formula}`).join("\n"),
      FOOTER,
    ].join("\n\n") + "\n"
  );
}
