/** Loads the stored series and latest readings the thesis metrics are computed from. */
import "server-only";
import { HSP029 } from "@/config/protocol";
import { HOUSE_OF_STAKE_CONTRACT } from "@/config/sources";
import { getEpochSupply } from "@/data/epochs";
import { getProposal } from "@/data/governance";
import { getIntentsReach, getReferralFeesDaily, getReferralWindow } from "@/data/intents-flows";
import { getNearAndPeers, getNearMarketCapHistory, getSupplyGrowth1y, getSupplyGrowthThrough } from "@/data/market";
import { getLatestValidators, getNetworkState, getProtocolVersions } from "@/data/network";
import { getNearPrices, getSeries } from "@/data/series";
import { SERIES } from "@/db/schema";

export type ThesisInputs = Awaited<ReturnType<typeof loadThesisInputs>>;

/** Every input of the thesis metrics, read in parallel. */
export async function loadThesisInputs() {
  const [
    market,
    supplyGrowth,
    supplyGrowthThrough,
    network,
    validatorSet,
    versions,
    epochs,
    hsp029,
    supply,
    buybackWallet,
    frontendWallet,
    oneClickWallet,
    fees,
    buybacks,
    volume,
    intentsFees,
    intentsRevenue,
    dexVolume,
    prices,
    minted,
    burnt,
    txns,
    active,
    newAccounts,
    txnFees,
    intentsTxns,
    marketCapHistory,
    treasuryBalance,
    intentsReach,
    defillamaVolume,
    swaps,
    confidentialVolume,
    tvl,
    confidentialTvl,
    referrals,
    referralFees,
  ] = await Promise.all([
    getNearAndPeers(),
    getSupplyGrowth1y(),
    getSupplyGrowthThrough(),
    getNetworkState(),
    getLatestValidators(),
    getProtocolVersions(),
    getEpochSupply(),
    getProposal(HOUSE_OF_STAKE_CONTRACT, HSP029.proposalId),
    getSeries(SERIES.nearTotalSupply),
    getSeries(SERIES.buybackWalletNear),
    getSeries(SERIES.frontendFeeWalletNear),
    getSeries(SERIES.oneClickFeeWalletNear),
    getSeries(SERIES.nearChainFeesUsd),
    getSeries(SERIES.intentsBuybacksUsd),
    getSeries(SERIES.intentsVolumeUsd),
    getSeries(SERIES.intentsFeesUsd),
    getSeries(SERIES.intentsRevenueUsd),
    getSeries(SERIES.nearDexVolumeUsd),
    getNearPrices(),
    getSeries(SERIES.mintedNear),
    getSeries(SERIES.burntNear),
    getSeries(SERIES.nearTxns),
    getSeries(SERIES.nearActiveAccounts),
    getSeries(SERIES.nearNewAccounts),
    getSeries(SERIES.nearTxnFeesNear),
    getSeries(SERIES.intentsTxns),
    getNearMarketCapHistory(),
    getSeries(SERIES.treasuryNear),
    getIntentsReach(),
    getSeries(SERIES.defillamaIntentsVolumeUsd),
    getSeries(SERIES.intentsSwaps),
    getSeries(SERIES.intentsConfidentialVolumeUsd),
    getSeries(SERIES.intentsTvlUsd),
    getSeries(SERIES.intentsConfidentialTvlUsd),
    getReferralWindow(30),
    getReferralFeesDaily(),
  ]);
  return {
    market,
    supplyGrowth,
    supplyGrowthThrough,
    network,
    validatorSet,
    versions,
    epochs,
    hsp029,
    supply,
    buybackWallet,
    frontendWallet,
    oneClickWallet,
    fees,
    buybacks,
    volume,
    intentsFees,
    intentsRevenue,
    dexVolume,
    prices,
    minted,
    burnt,
    txns,
    active,
    newAccounts,
    txnFees,
    intentsTxns,
    marketCapHistory,
    treasuryBalance,
    intentsReach,
    defillamaVolume,
    swaps,
    confidentialVolume,
    tvl,
    confidentialTvl,
    referrals,
    referralFees,
  };
}
